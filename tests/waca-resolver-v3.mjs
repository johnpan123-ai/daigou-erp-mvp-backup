import assert from 'node:assert/strict';
import {createServer} from 'vite';
const vite=await createServer({configFile:false,server:{middlewareMode:true},appType:'custom'});
try {
  const core=await vite.ssrLoadModule('/src/waca/orderCore.ts');
  const names=await vite.ssrLoadModule('/src/waca/nameEvidence.ts');
  const storage=await vite.ssrLoadModule('/src/waca/nextStorage.ts');
  const row=(change={})=>({productCode:'GP-DISCOVER',productTitle:'Product 2026',specCode:'',spec1:'Red',spec2:'',orderNumber:'A',orderStatus:'處理中',purchasedAt:'2026-10-05',quantity:1,subtotal:100,...change});
  const variant=(change={})=>({mainCode:'',childCode:'G-RED',variantId:'red',productGroupId:'parent',productTitle:'【小河馬日本代購】預購 27年03月 Product 2026',variantTitle:'Red',active:true,...change});
  const red=variant(),blue=variant({childCode:'G-BLUE',variantId:'blue',variantTitle:'Blue'});
  const match=(r,master=[red,blue])=>core.matchWacaItem(r,core.indexWacaMaster(master));
  assert.equal(match(row({specCode:'G-RED',productCode:'G-RED'})).resolution,'SPEC_CODE_EXACT');
  assert.equal(match(row({specCode:'G-BLUE'})).candidate.variantId,'blue');
  assert.equal(match(row({specCode:'MISSING'})).candidate,null);
  assert.equal(match(row()).resolution,'PRODUCT_UNIQUE_SPEC');
  assert.equal(match(row({spec1:''}),[red]).resolution,'PRODUCT_SINGLE_VARIANT');
  assert.equal(match(row({spec1:''})).resolution,'PENDING_AMBIGUOUS');
  assert.equal(match(row({productCode:''}),[red]).candidate,null);
  assert.equal(match(row({productTitle:'Product 2025'})).candidate,null,'year is semantic');
  assert.equal(match(row({productTitle:'Product ①'}),[variant({productTitle:'Product 1'})]).candidate,null,'circled numerals are not width aliases');
  assert.equal(match(row({productTitle:'Product 2026 Extra'})).candidate,null,'no substring identity');
  assert.equal(match(row({productTitle:'2026 Product'})).resolution,'GLOBAL_UNIQUE_COMBINATION');
  assert.equal(match(row({productTitle:'Product Product 2026'})).candidate,null,'token multiplicity preserved');
  assert.equal(names.wacaProductKey(' 【小河馬日本代購】 預購 27年03月 Ｐｒｏｄｕｃｔ【2026】 '),'PRODUCT2026');
  assert.equal(names.wacaProductKey('Product 活動2026年03月'),'PRODUCT活動2026年03月');
  assert.equal(match(row({spec1:'Red【L】'}),[variant({variantTitle:'Red(L)'})]).candidate.variantId,'red');
  assert.equal(match(row({spec1:'Red',spec2:'L'}),[variant({variantTitle:'RedL'})]).candidate,null);
  const alias=variant({productTitle:'代理版 Product 2026'});
  assert.equal(match(row(),[alias]).resolution,'ALIAS_UNIQUE');
  assert.equal(match(row(),[alias,variant({productGroupId:'other',variantId:'other',childCode:'G-OTHER',productTitle:'代理版 Product 2026'})]).resolution,'PENDING_AMBIGUOUS');
  assert.equal(match(row(),[alias,variant({variantId:'other',childCode:'G-OTHER',productTitle:alias.productTitle})]).resolution,'PENDING_AMBIGUOUS');
  const other=variant({productGroupId:'other',variantId:'other',childCode:'G-OTHER',variantTitle:'Other'});
  assert.equal(match(row(),[red,other]).resolution,'PRODUCT_SPEC_EXACT');
  assert.equal(match(row(),[red,variant({variantId:'duplicate',childCode:'G-DUP'})]).candidate,null,'equal spec cannot pick first');
  const repo=core.createWacaRepository();
  // Placeholder comes first: batch-wide discovery, not array-order guessing.
  core.importWacaRows([row({productTitle:'Placeholder',spec1:'Blue',orderNumber:'B'}),row()],repo,[red,blue],'learn');
  assert.equal(repo.items.size,2);assert.equal(repo.autoQuantities.get('blue'),1);
  assert.equal([...repo.mappings.values()].find(m=>m.productVariantId==='red').myacgMainId,'GP-DISCOVER');
  const variants=[red,blue].map(v=>({id:v.variantId,product_group_id:v.productGroupId,myacg_item_code:v.childCode,product_title:v.productTitle,variant_name:v.variantTitle}));
  const blank={revision:0,orders:[],items:[],mappings:[],masterLinks:[],batches:[]};
  const saved=storage.snapshotFromRepository(blank,repo,[]);
  const restored=storage.repositoryFromSnapshot(JSON.parse(JSON.stringify(saved)),variants);
  // Persisted mapping remains sufficient after the original proving ORDER is removed in an isolated fixture.
  restored.items=new Map([...restored.items].filter(([,item])=>item.productTitle==='Placeholder'));
  core.importWacaRows([],restored,[red,blue],'next-session');
  assert.equal(restored.autoQuantities.get('blue'),1,'current-Catalog-revalidated persistent parent learning');
  const expanding=core.createWacaRepository();
  core.importWacaRows([row({spec1:''})],expanding,[red],'single');
  core.importWacaRows([],expanding,[red,blue],'expanded');assert.equal(expanding.autoQuantities.size,0);
  const conflicting=core.createWacaRepository();
  const distinct=variant({productTitle:'Different product',productGroupId:'different',variantId:'different',childCode:'G-DIFF'});
  core.importWacaRows([row(),row({productTitle:'Different product',orderNumber:'B'})],conflicting,[red,distinct],'conflicting-gp');
  assert.equal(conflicting.autoQuantities.size,0,'contradictory GP proofs block ALL blank-spec rows');
  const baseline=JSON.stringify([...repo.autoQuantities]);
  for(let n=0;n<5;n++)core.importWacaRows([row()],repo,[red,blue],'repeat');
  assert.equal(JSON.stringify([...repo.autoQuantities]),baseline);assert.equal(repo.mappings.size,2);
  const status=core.createWacaRepository();
  core.importWacaRows([row(),row({orderNumber:'C',orderStatus:'取消'}),row({orderNumber:'F',orderStatus:'失敗'}),row({orderNumber:'P',orderStatus:'完成付款'}),row({orderNumber:'COUPON',productCode:'coupon'})],status,[red],'status');
  assert.equal(status.items.size,4);assert.equal(status.autoQuantities.get('red'),2);
  console.log('PASS Resolver V3: exact/equal SKU, global name/spec, unique/single, full tokens, alias collisions, semantic preservation, parent learning/JSON restore, contradictory GP, AUTO revalidation, historical/status/coupon/idempotency');
} finally {await vite.close();}
